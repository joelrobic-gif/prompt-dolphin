export function t(key: TranslationKey, lang: LangId): string {
  return TRANSLATIONS[lang]?.[key] ?? TRANSLATIONS.en[key] ?? key;
}

export function detectInitialLang(): LangId {
  if (typeof window === 'undefined') return 'en';
  const stored = window.localStorage?.getItem('pd_lang');
  if (stored && stored in LANGUAGES) return stored as LangId;
  const nav = window.navigator?.language || 'en';
  const full = nav.toLowerCase();
  const short = full.split('-')[0];
  if (full === 'zh-tw' || full === 'zh-hk') return 'zh-TW';
  if (full.startsWith('zh')) return 'zh-CN';
  if (short in LANGUAGES) return short as LangId;
  return 'en';
}

export function persistLang(lang: LangId): void {
  if (typeof window === 'undefined') return;
  try { window.localStorage.setItem('pd_lang', lang); } catch { /* ignore */ }
}
